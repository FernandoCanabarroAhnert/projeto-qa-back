CREATE TABLE IF NOT EXISTS colaborador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    matricula VARCHAR(255) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    salario_base NUMERIC(38, 2) NOT NULL,
    tipo_colaborador VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT colaborador_pkey PRIMARY KEY (id),
    CONSTRAINT uk_colaborador_matricula UNIQUE (matricula),
    CONSTRAINT colaborador_tipo_colaborador_check
        CHECK (
            tipo_colaborador IN ('PADRAO', 'COMISSIONADO', 'PRODUCAO')
        )
);

CREATE TABLE IF NOT EXISTS colaborador_comissionado (
    porcentagem_comissao NUMERIC(38, 2) NOT NULL,
    valor_vendas NUMERIC(38, 2) NOT NULL,
    id BIGINT NOT NULL,

    CONSTRAINT colaborador_comissionado_pkey PRIMARY KEY (id),
    CONSTRAINT fk_colaborador_comissionado
        FOREIGN KEY (id)
        REFERENCES colaborador (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS colaborador_padrao (
    id BIGINT NOT NULL,

    CONSTRAINT colaborador_padrao_pkey PRIMARY KEY (id),
    CONSTRAINT fk_colaborador_padrao
        FOREIGN KEY (id)
        REFERENCES colaborador (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS colaborador_producao (
    quantidade_produzida INTEGER NOT NULL,
    valor_unidade_produzida NUMERIC(38, 2) NOT NULL,
    id BIGINT NOT NULL,

    CONSTRAINT colaborador_producao_pkey PRIMARY KEY (id),
    CONSTRAINT fk_colaborador_producao
        FOREIGN KEY (id)
        REFERENCES colaborador (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);