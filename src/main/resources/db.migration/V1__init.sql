CREATE TABLE IF NOT EXISTS colaborador
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    matricula character varying(255) NOT NULL,
    nome character varying(255) NOT NULL,
    salario_base numeric(38,2) NOT NULL,
    tipo_colaborador character varying(255) NOT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT colaborador_pkey PRIMARY KEY (id),
    CONSTRAINT ukdnnhvr68rfwe47gasygd3nvx2 UNIQUE (matricula),
    CONSTRAINT colaborador_tipo_colaborador_check CHECK (tipo_colaborador::text = ANY (ARRAY['PADRAO'::character varying, 'COMISSIONADO'::character varying, 'PRODUCAO'::character varying]::text[]))
);

CREATE TABLE IF NOT EXISTS colaborador_comissionado
(
    porcentagem_comissao numeric(38,2) NOT NULL,
    valor_vendas numeric(38,2) NOT NULL,
    id bigint NOT NULL,
    CONSTRAINT colaborador_comissionado_pkey PRIMARY KEY (id),
    CONSTRAINT fkqwag4i3k892tf7g4f9b451gc3 FOREIGN KEY (id)
        REFERENCES colaborador (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS colaborador_padrao
(
    id bigint NOT NULL,
    CONSTRAINT colaborador_padrao_pkey PRIMARY KEY (id),
    CONSTRAINT fk7x3ffud7u1db3uwyixdmu4l0r FOREIGN KEY (id)
